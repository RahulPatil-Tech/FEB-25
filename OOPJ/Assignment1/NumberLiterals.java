public class NumberLiterals {
    public static void main(String[] args) {
        int binary = 0b1011;
        int octal = 012;           
        int hexadecimal = 0x1A;     
        double floatingPoint = 1.23;

        System.out.println("Binary literal: " + binary);
        System.out.println("Octal literal: " + octal);
        System.out.println("Hexadecimal literal: " + hexadecimal);
        System.out.println("Floating-point literal: " + floatingPoint);
    }
}
