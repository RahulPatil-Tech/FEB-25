public class AverageOfInts {
    public static void main(String[] args) {
        int num1 = 10;
        int num2 = 20;
        int num3 = 30;
        double average = (double) (num1 + num2 + num3) / 3;
        System.out.println("Average of " + num1 + ", " + num2 + ", " + num3 + " is: " + average);
    }
}
